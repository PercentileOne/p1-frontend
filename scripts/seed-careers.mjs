// ── Main seed loop ─────────────────────────────────────────────────────────────

async function seed() {
  const seededIds = loadProgress();
  const remaining = CAREERS.filter(c => !seededIds.has(c.title.toLowerCase().replace(/[^a-z0-9]+/g, '-')));

  console.log(`\n🚀 Career Seed — ${CAREERS.length} total, ${remaining.length} to process\n`);

  let seeded = 0;
  let failed = 0;

  for (let i = 0; i < remaining.length; i += BATCH_SIZE) {
    const batch = remaining.slice(i, i + BATCH_SIZE);
    const batchNum = Math.floor(i / BATCH_SIZE) + 1;
    const totalBatches = Math.ceil(remaining.length / BATCH_SIZE);

    process.stdout.write(`[${batchNum}/${totalBatches}] ${batch.map(c => c.title).join(', ')} ... `);

    try {
      const careers = await generateCareers(batch);

      for (const career of careers) {
        if (!career.id) career.id = career.title.toLowerCase().replace(/[^a-z0-9]+/g, '-');
        if (!career.category) {
          const match = batch.find(b => b.title === career.title);
          career.category = match?.category ?? 'General';
          career.subcategory = match?.subcategory ?? '';
        }
        await container.items.upsert(career);
        seededIds.add(career.id);
        seeded++;
      }

      saveProgress(seededIds);
      console.log(`✅ ${careers.length} done`);
    } catch (err) {
      console.log(`❌ ${err.message}`);
      failed += batch.length;
    }

    if (i + BATCH_SIZE < remaining.length) {
      await new Promise(r => setTimeout(r, DELAY_MS));
    }
  }

  console.log(`\n✅ Complete — ${seeded} upserted, ${failed} failed`);
  console.log(`📊 Total in Cosmos: ~${seededIds.size} careers`);
  if (failed > 0) console.log(`💡 Re-run with --resume to retry failed batches\n`);
}

seed().catch(console.error);
