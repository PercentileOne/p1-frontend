// ── Progress tracking ──────────────────────────────────────────────────────────

function loadProgress() {
  if (RESUME && fs.existsSync(PROGRESS_FILE)) {
    return new Set(JSON.parse(fs.readFileSync(PROGRESS_FILE, 'utf8')).seeded);
  }
  return new Set();
}

function saveProgress(seededIds) {
  fs.writeFileSync(PROGRESS_FILE, JSON.stringify({ seeded: [...seededIds], ts: new Date().toISOString() }));
}

