// Generates the country list used by the "Try it live" demo from ONE source, so the three places that need it can never drift apart:
//   1. src/frontend/src/data/countries.ts                       (the /try form)
//   2. src/backend/Explain.Api/Features/TryOut/TryOutCountries.cs (server-side validation + the name the question prompt uses)
//   3. src/viewme/public/home-v2.html                            (the homepage form; the block between the COUNTRIES markers)
//
// The list is the 249 officially assigned ISO 3166-1 alpha-2 codes plus Kosovo (XK, not ISO but widely used). English names come from the
// platform's own ICU data (Intl.DisplayNames), with a handful of friendlier overrides below. Historic/pseudo codes that ICU also knows
// (YU, SU, DD, FX, AN …) are excluded on purpose because they are not in the ISO list.
//
// Run from the repo root:  node scripts/generate-country-data.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const ISO_3166_1 = `AD AE AF AG AI AL AM AO AQ AR AS AT AU AW AX AZ BA BB BD BE BF BG BH BI BJ BL BM BN BO BQ BR BS BT BV BW BY BZ CA CC CD CF CG CH CI CK CL CM CN CO CR CU CV CW CX CY CZ DE DJ DK DM DO DZ EC EE EG EH ER ES ET FI FJ FK FM FO FR GA GB GD GE GF GG GH GI GL GM GN GP GQ GR GS GT GU GW GY HK HM HN HR HT HU ID IE IL IM IN IO IQ IR IS IT JE JM JO JP KE KG KH KI KM KN KP KR KW KY KZ LA LB LC LI LK LR LS LT LU LV LY MA MC MD ME MF MG MH MK ML MM MN MO MP MQ MR MS MT MU MV MW MX MY MZ NA NC NE NF NG NI NL NO NP NR NU NZ OM PA PE PF PG PH PK PL PM PN PR PS PT PW PY QA RE RO RS RU RW SA SB SC SD SE SG SH SI SJ SK SL SM SN SO SR SS ST SV SX SY SZ TC TD TF TG TH TJ TK TL TM TN TO TR TT TV TW TZ UA UG UM US UY UZ VA VC VE VG VI VN VU WF WS YE YT ZA ZM ZW`.split(/\s+/);
const EXTRA = ['XK'];

// Friendlier than ICU's defaults (these read like the names people actually use).
const OVERRIDES = {
  CD: 'Democratic Republic of the Congo',
  CG: 'Republic of the Congo',
  HK: 'Hong Kong',
  MO: 'Macao',
  MM: 'Myanmar',
};

const dn = new Intl.DisplayNames(['en'], { type: 'region' });
const countries = [...ISO_3166_1, ...EXTRA]
  .map(code => ({ code, name: OVERRIDES[code] ?? dn.of(code) }))
  .filter(c => c.name && c.name !== c.code);
if (countries.length !== 250) throw new Error(`Expected 250 countries, got ${countries.length}`);
countries.sort((a, b) => a.name.localeCompare(b.name, 'en'));

const root = resolve(import.meta.dirname, '..');
const HEADER = 'GENERATED by scripts/generate-country-data.mjs — do not edit by hand; re-run the script.';

// 1. Frontend module
writeFileSync(resolve(root, 'src/frontend/src/data/countries.ts'),
`// ${HEADER}
export interface Country { code: string; name: string }

/** ISO 3166-1 alpha-2 country codes with full English names, sorted by name. */
export const COUNTRIES: readonly Country[] = [
${countries.map(c => `  { code: '${c.code}', name: '${c.name.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}' },`).join('\n')}
];

const BY_CODE = new Map(COUNTRIES.map(c => [c.code, c.name]));
export const countryName = (code: string | null | undefined): string | undefined => (code ? BY_CODE.get(code.toUpperCase()) : undefined);
`);

// 2. Backend
writeFileSync(resolve(root, 'src/backend/Explain.Api/Features/TryOut/TryOutCountries.cs'),
`// ${HEADER}
namespace Explain.Api.Features.TryOut;

/// <summary>ISO 3166-1 alpha-2 codes (plus Kosovo) and their English names. Used to validate the country a /try visitor picks and to name it in the question prompt.</summary>
public static class TryOutCountries
{
    private static readonly Dictionary<string, string> Names = new(StringComparer.OrdinalIgnoreCase)
    {
${countries.map(c => `        ["${c.code}"] = ${JSON.stringify(c.name)},`).join('\n')}
    };

    /// <summary>The English name for a valid country code, or null when the code isn't one we know.</summary>
    public static string? NameFor(string? code) =>
        !string.IsNullOrWhiteSpace(code) && Names.TryGetValue(code.Trim(), out var name) ? name : null;
}
`);

// 3. Homepage (static HTML): replace the block between the markers
const htmlPath = resolve(root, 'src/viewme/public/home-v2.html');
let html = readFileSync(htmlPath, 'utf8');
const begin = '/* COUNTRIES:BEGIN (generated by scripts/generate-country-data.mjs) */';
const end = '/* COUNTRIES:END */';
const a = html.indexOf(begin), b = html.indexOf(end);
if (a === -1 || b === -1) {
  console.log('Homepage markers not found yet — skipping home-v2.html (add the COUNTRIES:BEGIN/END block, then re-run).');
} else {
  const arr = 'var COUNTRIES = ' + JSON.stringify(countries.map(c => [c.code, c.name])) + ';';
  html = html.slice(0, a) + begin + '\n' + arr + '\n' + end + html.slice(b + end.length);
  writeFileSync(htmlPath, html);
}
console.log(`Wrote ${countries.length} countries.`);
